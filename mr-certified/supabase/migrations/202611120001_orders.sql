-- MERQO: persist orders and enforce pricing, stock, and status changes in SQL.
-- Requires the existing profiles, user_roles, products, and is_admin() schema.

create table if not exists public.orders (
  id           bigint generated by default as identity primary key,
  buyer_id     uuid not null references auth.users(id) on delete restrict,
  seller_id    uuid references auth.users(id) on delete set null,
  product_id   bigint references public.products(id) on delete set null,
  product_name text not null,
  seller_name  text not null,
  size         text not null default '',
  qty          integer not null check (qty between 1 and 99),
  unit_price   integer not null check (unit_price >= 0),
  amount       integer not null check (amount >= 0),
  stage        smallint not null default 0 check (stage between 0 and 4),
  buyer_name   text not null default '',
  buyer_email  text not null default '',
  buyer_phone  text not null default '',
  address      jsonb not null default '{}'::jsonb,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create index if not exists orders_buyer_idx on public.orders (buyer_id, created_at desc);
create index if not exists orders_seller_idx on public.orders (seller_id, created_at desc);

alter table public.orders enable row level security;
revoke all on public.orders from anon, authenticated;
grant select on public.orders to authenticated;

drop policy if exists "orders: buyer reads own" on public.orders;
create policy "orders: buyer reads own" on public.orders for select to authenticated
  using ((select auth.uid()) = buyer_id);
drop policy if exists "orders: seller reads own" on public.orders;
create policy "orders: seller reads own" on public.orders for select to authenticated
  using ((select auth.uid()) = seller_id);
drop policy if exists "orders: admin reads all" on public.orders;
create policy "orders: admin reads all" on public.orders for select to authenticated
  using (public.is_admin());

create or replace function public.place_orders(p_items jsonb)
returns setof public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_prof public.profiles%rowtype;
  v_item jsonb;
  v_prod public.products%rowtype;
  v_qty int;
  v_size text;
  v_row public.orders%rowtype;
begin
  if v_user is null then raise exception 'Please sign in first.'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 30 then
    raise exception 'Your cart is empty or too large.';
  end if;
  select * into v_prof from public.profiles where id = v_user;
  if not found then raise exception 'Your account profile is missing.'; end if;
  if not exists (select 1 from public.user_roles where user_id = v_user and role = 'buyer' and status = 'approved') then
    raise exception 'Buyer access is needed to place orders. Use a buyer account.';
  end if;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := coalesce((v_item->>'qty')::int, 1);
    v_size := coalesce(v_item->>'size', '');
    if v_qty < 1 or v_qty > 99 then raise exception 'Invalid quantity.'; end if;

    select * into v_prod from public.products
      where id = (v_item->>'pid')::bigint and status = 'active' for update;
    if not found then raise exception 'A product in your cart is no longer available.'; end if;
    if v_prod.seller_id = v_user then raise exception 'You cannot order your own product.'; end if;
    if v_prod.stock is not null and v_prod.stock < v_qty then
      raise exception '% has only % left in stock.', v_prod.name, v_prod.stock;
    end if;
    if v_prod.stock is not null then
      update public.products set stock = stock - v_qty where id = v_prod.id;
    end if;

    insert into public.orders (buyer_id, seller_id, product_id, product_name, seller_name, size, qty,
                               unit_price, amount, buyer_name, buyer_email, buyer_phone, address)
    values (v_user, v_prod.seller_id, v_prod.id, v_prod.name, coalesce(v_prod.seller_name, ''), left(v_size, 20), v_qty,
            v_prod.price, v_prod.price * v_qty,
            trim(concat_ws(' ', v_prof.first_name, v_prof.last_name)), coalesce(v_prof.email, ''),
            coalesce(v_prof.phone, ''), coalesce(v_prof.address, '{}'::jsonb))
    returning * into v_row;
    return next v_row;
  end loop;
  return;
end;
$$;
revoke all on function public.place_orders(jsonb) from public, anon;
grant execute on function public.place_orders(jsonb) to authenticated;

create or replace function public.advance_order(p_order bigint, p_stage int)
returns public.orders
language plpgsql
security definer
set search_path = public
as $$
declare
  v_user uuid := auth.uid();
  v_ord public.orders%rowtype;
begin
  if v_user is null then raise exception 'Please sign in first.'; end if;
  select * into v_ord from public.orders where id = p_order for update;
  if not found then raise exception 'Order not found.'; end if;
  if p_stage <= v_ord.stage then raise exception 'This order is already at that step.'; end if;

  if v_user = v_ord.seller_id then
    if p_stage not between 1 and 3 then raise exception 'Sellers can mark an order packed, shipped or out for delivery.'; end if;
  elsif v_user = v_ord.buyer_id then
    if p_stage <> 4 or v_ord.stage < 2 then raise exception 'You can confirm receipt once the order has shipped.'; end if;
  else
    raise exception 'This is not your order.';
  end if;

  update public.orders set stage = p_stage, updated_at = now() where id = p_order returning * into v_ord;
  return v_ord;
end;
$$;
revoke all on function public.advance_order(bigint, int) from public, anon;
grant execute on function public.advance_order(bigint, int) to authenticated;
